#!/usr/bin/env python3
"""Regenerate docs/KEYBINDINGS.md from the in-app keymap (single source of truth).

    python scripts/gen_keybindings.py          # write the file
    python scripts/gen_keybindings.py --check  # exit 1 if the file is stale
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from trace_zero.ui.keymap import FILTER_HELP, KEYMAP  # noqa: E402

TARGET = ROOT / "docs" / "KEYBINDINGS.md"


def render() -> str:
    out = [
        "# Keyboard reference",
        "",
        "<!-- Generated by scripts/gen_keybindings.py from src/trace_zero/ui/keymap.py. Do not edit by hand. -->",
        "",
        "TRACE//ZERO is fully keyboard driven; a mouse is never required. Press `?` inside",
        "the application for the same reference. Global keys are disabled while a dialog with a",
        "text field is open, so typing `q` or `space` into a filter never quits or starts a replay.",
        "",
    ]
    for section, keys in KEYMAP:
        out += [f"## {section.title()}", "", "| Key | Action |", "| --- | --- |"]
        out += [f"| `{k}` | {d} |" for k, d in keys]
        out.append("")
    out += ["## Filter syntax (`/`)", "", "| Term | Meaning |", "| --- | --- |"]
    out += [f"| `{k}` | {d} |" for k, d in FILTER_HELP]
    out += [
        "",
        "Terms are combined with AND. Within one term, `|` or `,` separate alternatives",
        "(`proto:dns|tls`, `port:80,443`). Prefix a term with `!` to negate it.",
        "",
    ]
    return "\n".join(out)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != text:
            print("docs/KEYBINDINGS.md is stale; run scripts/gen_keybindings.py")
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
